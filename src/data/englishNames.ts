export const ENGLISH_NAMES: ReadonlyMap<string, string> = new Map(TABLE);

/** 日本語（かな・漢字・全角記号）を含むか */
export const hasJapanese = (text: string) => /[\u3000-\u30ff\u4e00-\u9fff\uff01-\uff5e]/.test(text);

/**
 * 英語名に日本語が残っていれば、対訳表の英語名に置き換える。
 * 「In front of …」「Near …」（名前のない分岐の目印）は、中の名前だけを置き換える。
 */
export function withEnglishName(text: LocalizedText): LocalizedText {
  if (!hasJapanese(text.en)) return text;
  const match = /^((?:In front of|Near) )?(.*)$/s.exec(text.en);
  const prefix = match?.[1] ?? '';
  const en = ENGLISH_NAMES.get(match?.[2] ?? text.en);
  return en === undefined ? text : { ...text, en: `${prefix}${en}` };
}
